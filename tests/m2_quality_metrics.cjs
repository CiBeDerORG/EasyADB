'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const root={};root.window=root;
vm.runInNewContext(fs.readFileSync('web/m2-metrics.js','utf8'),root,{filename:'m2-metrics.js'});
const {QualityMeter,format}=root.EasyADBMetrics;
let quality={totalVideoFrames:0,droppedVideoFrames:0};
const video={currentTime:1,
 getVideoPlaybackQuality:()=>quality};
const meter=new QualityMeter(0);
meter.recordBytes(1000000);
let sample=meter.sample(video,1000,{receiveMbps:8,procCpuPct:20,procRssMib:50});
assert.equal(sample.fps,null);
quality={totalVideoFrames:31,droppedVideoFrames:1};
sample=meter.sample(video,2000,{receiveMbps:8,frameAgeMs:15,procCpuPct:30,procRssMib:70});
assert.equal(sample.fps,30,'total frames includes dropped frame');
assert.ok(Math.abs(sample.dropPct-100/31)<0.00001);
assert.equal(Object.hasOwn(sample,'bufferAhead'),false,'WebRTC must not expose obsolete MSE buffer estimates');
assert.equal(Object.hasOwn(sample,'queueBytes'),false,'WebRTC receiver has no MSE append queue');
assert.doesNotMatch(format(sample),/缓冲余量|待追加/);
assert.equal(sample.totalBytes,1000000);
assert.match(format(sample),/不代表手机到屏幕的端到端延迟/);
const summary=meter.summary('baseline','Phone');
assert.equal(summary.profile,'baseline');assert.equal(summary.totalBytes,1000000);
assert.equal(summary.avgReceiveMbps,8);
assert.equal(summary.avgCpuPct,25);
assert.equal(summary.avgRssMib,60);
const paused={currentTime:0,getVideoPlaybackQuality(){return quality;}};
sample=meter.sample(paused,3000,{});assert.equal(sample.fps,0,'stationary frame does not force fake FPS');
const fallback=new QualityMeter(0);
const plain={currentTime:0};
fallback.sample(plain,1000,{renderedFrames:20});
assert.equal(fallback.sample(plain,2000,{renderedFrames:40}).fps,20,'RVFC fallback');
console.log('M2 measured quality contract passed');
